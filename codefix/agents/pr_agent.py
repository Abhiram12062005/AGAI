"""PR agent (the Tester/PR role's second half).

prepare(): on Manager approval of a passing TestReport, commit the verified patch to a new
           codefix/<task_id> branch inside the isolated workspace. Nothing leaves the machine.
open():    push + open the Pull Request — only called after explicit human confirmation
           (UI button / CLI prompt), never automatically, never to the default branch.
"""

from __future__ import annotations

from codefix.agents.base import RunContext
from codefix.blackboard import Diagnosis, Patch, PRResult, TestReport


def branch_name(task_id: str) -> str:
    return f"codefix/{task_id}"


def pr_body(ctx: RunContext, diagnosis: Diagnosis | None, patch: Patch, report: TestReport) -> str:
    cites = "\n".join(f"- `{c}`" for c in (patch.citations + (diagnosis.citations if diagnosis else []))) or "- (none)"
    return (f"## Bug\n{ctx.bug_report}\n\n## Root cause (Diagnoser)\n{diagnosis.root_cause if diagnosis else 'n/a'}\n\n"
            f"## Fix (Fixer, attempt {patch.attempt_no})\n{patch.rationale}\n\n"
            f"## Verification (Tester)\n{report.total} tests run, {report.failed} failed, "
            f"{len(report.lint_findings)} lint findings, {report.duration_ms} ms.\n\n"
            f"## Retrieved context cited\n{cites}\n\n---\nGenerated by CodeFix AI · task `{ctx.task_id}`")


def prepare(ctx: RunContext, patch: Patch, report: TestReport, diagnosis: Diagnosis | None) -> PRResult:
    ws = report.workspace
    branch = branch_name(ctx.task_id)
    ctx.tool("pr", "git_branch", workspace=ws, branch=branch)
    title = f"codefix: {(diagnosis.root_cause if diagnosis else ctx.bug_report).splitlines()[0][:60]}"
    sha = ctx.tool("pr", "git_commit", workspace=ws, message=f"{title}\n\n{patch.rationale}\n\nCodeFix-Task: {ctx.task_id}")["sha"]
    # Accepted fix -> 'bugs' RAG collection, so future runs can retrieve it.
    try:
        ctx.tool("pr", "record_fix", task_id=ctx.task_id, bug_report=ctx.bug_report,
                 root_cause=diagnosis.root_cause if diagnosis else "", diff=patch.diff, files=patch.files_touched)
    except Exception as e:
        ctx.event("rag_error", agent="pr", error=str(e))
    return PRResult(branch=branch, commit_sha=sha, pushed=False,
                    note=f"Committed in isolated workspace {ws}. Awaiting human confirmation to push/open PR.")


def open_pr(ctx: RunContext, patch: Patch, report: TestReport, diagnosis: Diagnosis | None,
            confirmed: bool) -> PRResult:
    branch = branch_name(ctx.task_id)
    title = f"codefix: {(diagnosis.root_cause if diagnosis else ctx.bug_report).splitlines()[0][:60]}"
    r = ctx.tool("pr", "open_pull_request", workspace=report.workspace, branch=branch, title=title,
                 body=pr_body(ctx, diagnosis, patch, report), confirmed=confirmed)
    return PRResult(branch=branch, url=r.get("url"), pushed=bool(r.get("pushed")), note=r.get("note", ""))
